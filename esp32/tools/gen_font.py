def cols(g):
    rows = g.split("|")
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), g
    return [sum(1 << r for r in range(7) if rows[r][c] == "#") for c in range(5)]


print("// 5x7 font for the SSD1306 transcript display, generated by esp32/tools/gen_font.py (drawn for this project).")
print("// font5x7[c - 32] = 5 column bytes, bit 0 = top row. Characters without a glyph render blank.")
print("#pragma once")
print("#include <stdint.h>")
print("static const uint8_t font5x7[95][5] = {")
for code in range(32, 127):
    ch = chr(code).lower()
    c = cols(G[ch]) if ch in G else [0] * 5
    print("    {" + ", ".join(f"0x{v:02x}" for v in c) + "},  // " + repr(chr(code)))
print("};")
